// Build per-site English maps (sites/<slug>/i18n.en.js) from tools/_i18n/{known,en}/<slug>.json,
// write a small shared fallback dictionary (tools/i18n-dict.js) and (re)inject the runtime tags.
// usage: node tools/i18n-build.cjs
const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const sitesDir = path.join(root, 'sites')
const dir = path.join(__dirname, '_i18n')
const read = (f) => (fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : {})

const slugs = fs.readdirSync(sitesDir).filter((d) => /^(qt-)?\d{2,3}-/.test(d) && fs.existsSync(path.join(sitesDir, d, 'index.html')))
const freq = {}
let withMap = 0
let totalKeys = 0
const TAGS = '<script src="i18n.en.js" defer></script><script src="../../tools/i18n-dict.js" defer></script><script src="../../tools/i18n-site.js" defer></script>'
for (const s of slugs) {
  const merged = { ...read(path.join(dir, 'known', `${s}.json`)), ...read(path.join(dir, 'en', `${s}.json`)) }
  for (const [k, v] of Object.entries(merged)) {
    if (typeof v !== 'string' || !v.trim()) delete merged[k]
    else {
      freq[k] = freq[k] || {}
      freq[k][v] = (freq[k][v] || 0) + 1
    }
  }
  if (Object.keys(merged).length) withMap++
  totalKeys += Object.keys(merged).length
  const js = '/* English map for the VI⇄EN switcher — generated by tools/i18n-build.cjs */\nwindow.__SITE_EN=' + JSON.stringify(merged).replace(/</g, '\\u003c') + ';\n'
  fs.writeFileSync(path.join(sitesDir, s, 'i18n.en.js'), js)

  // inject / normalise runtime tags, keeping the html mtime (thumbnail cache relies on it)
  const htmlPath = path.join(sitesDir, s, 'index.html')
  const st = fs.statSync(htmlPath)
  let html = fs.readFileSync(htmlPath, 'utf8')
  const before = html
  html = html.replace(/(?:<script src="i18n\.en\.js" defer><\/script>)?<script src="\.\.\/\.\.\/tools\/i18n-dict\.js" defer><\/script><script src="\.\.\/\.\.\/tools\/i18n-site\.js" defer><\/script>\n?/g, '')
  html = html.replace(/<\/body>/i, TAGS + '\n</body>')
  if (!/<\/body>/i.test(before)) html += '\n' + TAGS + '\n'
  if (html !== before) {
    fs.writeFileSync(htmlPath, html)
    fs.utimesSync(htmlPath, st.atime, st.mtime)
  }
}

// Shared fallback: strings that appear on 3+ sites with a dominant translation
const common = {}
for (const [k, vs] of Object.entries(freq)) {
  const entries = Object.entries(vs).sort((a, b) => b[1] - a[1])
  const n = entries.reduce((a, e) => a + e[1], 0)
  if (n >= 3 && k.length <= 60) common[k] = entries[0][0]
}
const extra = {
  'Danh mục': 'Catalog',
  'Đóng': 'Close',
  'Mở': 'Open',
  'Hủy': 'Cancel',
  'Lưu': 'Save',
  'Xóa': 'Delete',
  'Tìm kiếm': 'Search',
  'Hôm nay': 'Today',
  'Hôm qua': 'Yesterday',
  'vừa xong': 'just now',
  'Bỏ qua đến nội dung chính': 'Skip to main content',
}
fs.writeFileSync(path.join(__dirname, 'i18n-dict.js'), '/* Shared VI→EN fallback — generated by tools/i18n-build.cjs */\nwindow.__AGY_I18N_DICT=' + JSON.stringify({ exact: { ...extra, ...common } }).replace(/</g, '\\u003c') + ';\n')
console.log({ sites: slugs.length, withMap, totalKeys, commonKeys: Object.keys(common).length })
